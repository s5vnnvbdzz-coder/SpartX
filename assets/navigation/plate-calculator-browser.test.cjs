'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
(async()=>{const browser=await chromium.launch({headless:true});try{
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await page.addInitScript(()=>{if(!localStorage.getItem('spartxToolsSettings'))localStorage.setItem('spartxToolsSettings',JSON.stringify({warmup:false,diagram:false,trainingMaxFinder:true,plates:{25:true,20:true,15:true,10:true,5:true,2.5:true,1.25:true}}));});
 const base='http://127.0.0.1:4173/';
 await page.goto(base+'index.html',{waitUntil:'load'});
 await page.evaluate(()=>window.spartanxNavigateScreen('tools',{instant:true}));
 const card=page.locator('#toolsReplica section[aria-labelledby="plateTitle"]');
 if(await card.evaluate(el=>el.classList.contains('is-collapsed')))await card.locator('.card-collapse').click();
 assert.equal(await card.locator('#plateSettings input').count(),7);
 await card.locator('#bar').fill('20');await card.locator('#target').fill('70');
 assert.match(await card.locator('#plates').innerText(),/1 × 25 kg/);
 await card.locator('[data-plate-size="25"]').uncheck();
 assert.doesNotMatch(await card.locator('#plates').innerText(),/25 kg/);
 assert.match(await card.locator('#plates').innerText(),/20 kg/);
 assert.equal(await card.locator('#plateOptions').isVisible(),true);
 assert.equal(await card.locator('#plateDiagramWrap').isVisible(),true);
 assert.equal(await card.locator('#plateDiagram > rect[data-bar-shaft]').count(),1);
 assert.equal(await card.locator('#plateDiagram > rect[data-bar-shaft]').getAttribute('height'),'8');
 assert.equal(await card.locator('#plateDiagram > rect[fill="#aeb7c0"],#plateDiagram > rect[fill="#737d87"]').count(),1);
 const before=await card.locator('#plates').innerText();
 await card.locator('#plateOptionsToggle').evaluate(el=>el.click());
 assert.equal(await card.locator('#plateOptions').isVisible(),false);
 assert.equal(await card.locator('#plateDiagramWrap').isVisible(),true);
 assert.equal(await card.locator('#plates').innerText(),before);
 await card.locator('#plateOptionsToggle').evaluate(el=>el.click());
 assert.equal(await card.locator('#plateOptions').isVisible(),true);
 assert.equal(await card.locator('[data-plate-size="25"]').isChecked(),false);
 await card.locator('#plateOptionsToggle').evaluate(el=>el.click());
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('spartxToolsSettings')));
 assert.equal(saved.plates[25],false);assert.equal(saved.diagram,false);assert.equal(saved.plateOptionsExpanded,false);assert.equal(saved.warmup,false);
 await page.goto(base+'tools/settings.html?return=tracker',{waitUntil:'load'});
 assert.equal(await page.locator('#plateSettings,#plateOptionsToggle,#diagramToggle').count(),0);
 await page.goto(base+'index.html',{waitUntil:'load'});
 await page.evaluate(()=>window.spartanxNavigateScreen('tools',{instant:true}));
 assert.equal(await card.locator('[data-plate-size="25"]').isChecked(),false);
 assert.equal(await card.locator('#plateOptionsToggle').isChecked(),false);
 assert.equal(await card.locator('#plateOptions').isVisible(),false);
 assert.equal(await card.locator('#plateDiagramWrap').isVisible(),true);
 for(const route of ['tools/index.html','tools/embedded.html']){
  await page.goto(base+route,{waitUntil:'load'});
  assert.equal(await page.locator('#plateSettings input').count(),7);
  assert.equal(await page.locator('[data-plate-size="25"]').isChecked(),false);
  assert.equal(await page.locator('#plateOptions').isVisible(),false);
  assert.equal(await page.locator('#plateDiagramWrap').isVisible(),true);
  assert.equal(await page.locator('#plateDiagram > rect[data-bar-shaft]').getAttribute('height'),'8');
 }
 console.log('PASS: inline plate choices, immediate recalculation, available plates toggle, always-visible slim bar, shared saved settings, no duplicate settings card');
 }finally{await browser.close();}})().catch(e=>{console.error(e);process.exit(1)});
