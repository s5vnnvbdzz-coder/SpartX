'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const code=fs.readFileSync(path.join(__dirname,'milestone-engine.js'),'utf8');
const w={};
vm.runInNewContext(code,{window:w});
const M=w.SpartanXMilestoneEngine;
assert.ok(M&&typeof M.snapshot==='function');
const session=(reps,weight=100)=>({exercises:[{name:'Back Squat',sets:[{weight,reps,done:true}]}]});
const s=[session(50),session(50),{exercises:[{name:'Rowing Machine',sets:[{weight:200,reps:200,done:true}]}]}];
const cardio=name=>name==='Rowing Machine';
const empty=M.snapshot([],null,{},cardio);
assert.equal(empty.values.workouts,0);
assert.equal(empty.earned,0);
assert.equal(empty.total,12);
assert.equal(empty.categories[0].nextGoal,100);
assert.equal(empty.categories[0].progress,0);
const counted=M.snapshot(s,null,{},cardio);
assert.equal(counted.values.workouts,3);
assert.equal(counted.values.reps,100,'Only saved resistance reps count');
assert.equal(counted.values.volume,10000,'Only resistance load contributes to tonnage');
assert.equal(counted.values.cycles,0);
const records=Array.from({length:100},()=>session(100,100));
const first=M.snapshot(records,null,{},cardio);
assert.equal(first.values.workouts,100);
assert.equal(first.values.reps,10000);
assert.equal(first.values.volume,1000000);
assert.equal(first.categories.find(x=>x.id==='workouts').unlocked,1);
assert.equal(first.categories.find(x=>x.id==='volume').unlocked,1);
assert.equal(first.categories.find(x=>x.id==='reps').unlocked,1);
assert.equal(first.earned,3);
assert.equal(first.categories.find(x=>x.id==='workouts').currentBadge,'Centurion');
assert.equal(first.categories.find(x=>x.id==='workouts').nextGoal,250);
const permanent=M.snapshot([],null,first.highWater,cardio);
assert.equal(permanent.earned,3,'Earned tier ownership must not reset when history changes');
assert.equal(permanent.categories.find(x=>x.id==='workouts').currentBadge,'Centurion');
const cycleId='2026-01-01T10:00:00.000Z';
const logs=['Back Squat','Bench Press','Deadlift'].map(lift=>({lift,week:6,cycleId,setsComplete:true}));
assert.equal(M.completedAscensionCycles({logs:logs.slice(0,2)}),0,'Incomplete 3-lift cycles not counted');
assert.equal(M.completedAscensionCycles({logs}),1,'Verified sixth week for every main lift completes a cycle');
assert.equal(M.completedAscensionCycles({logs:[...logs,{...logs[0]}]}),1,'Duplicate logs do not inflate completions');
assert.equal(M.completedAscensionCycles({logs:logs.map(log=>({...log,setsComplete:false}))}),0);
assert.equal(M.completedAscensionCycles({logs:logs.map(log=>({...log,cycleId:null}))}),0,
 'Historical logs without verifiable cycle IDs are not guessed');
const cycle3={logs:[0,1,2].flatMap(i=>logs.map(log=>({...log,cycleId:
 new Date(Date.parse(cycleId)+i*86400000*50).toISOString()})))};
assert.equal(M.completedAscensionCycles(cycle3),3);
const asc=M.snapshot([],cycle3,{},cardio);
assert.equal(asc.categories.find(x=>x.id==='cycles').unlocked,2);
assert.equal(asc.categories.find(x=>x.id==='cycles').nextGoal,6);
const high=M.snapshot(Array.from({length:500},()=>session(200,100)),cycle3,{},cardio);
assert.equal(high.categories.find(x=>x.id==='workouts').unlocked,3);
assert.equal(high.categories.find(x=>x.id==='volume').unlocked,2);
assert.equal(high.categories.find(x=>x.id==='reps').unlocked,3);
assert.equal(high.categories.find(x=>x.id==='cycles').unlocked,2);
assert.equal(high.values.volume,10000000);
assert.equal(high.earned,10);
const root=fs.readFileSync(path.join(__dirname,'../../index.html'),'utf8');
const css=fs.readFileSync(path.join(__dirname,'milestone-modal.css'),'utf8');
const ui=fs.readFileSync(path.join(__dirname,'milestone-modal.js'),'utf8');
assert(root.includes('milestone-engine.js?v=379')&&root.includes('milestone-modal.js?v=379'));
assert(root.includes('milestone-modal.css?v=379'));
assert(ui.includes("grid.insertAdjacentElement('beforebegin',entry)"),'Entry lives inside existing badge collection');
assert(ui.includes("document.body.classList.add('sx-milestones-open')"),'Modal hides app chrome');
assert(css.includes('body.sx-milestones-open #trackerNav'),'Bottom navigation hidden within popup');
assert(css.includes('height:100dvh'),'Mobile overlay covers full viewport');
assert(ui.includes('aria-modal="true"')&&ui.includes("event.key==='Escape'"),
 'Dialog supports modal semantics and Escape dismissal');
console.log('PASS: four lifetime milestone paths, progress, permanent tiers, verifiable AscensionX cycles and no-nav modal');
